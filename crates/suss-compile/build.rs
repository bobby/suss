//! Fingerprint the implementation that produces portable artifacts, and
//! generate the bootstrap artifacts it embeds (#383).
include!("build_identity.rs");

fn main() {
    let crate_root = std::path::PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let root = crate_root.parent().unwrap().parent().unwrap().to_path_buf();
    let identity = compiler_identity(&root);
    println!("cargo:rustc-env=SUSS_COMPILER_SOURCE_SHA256={identity}");
    // `suss_host`: the native compiler host, with wasmtime. Not a wasm target.
    println!("cargo:rustc-check-cfg=cfg(suss_host)");
    println!("cargo:rustc-check-cfg=cfg(suss_generator)");
    if std::env::var("CARGO_CFG_TARGET_FAMILY").map_or(true, |family| !family.split(',').any(|f| f == "wasm")) {
        println!("cargo:rustc-cfg=suss_host");
    }
    // The bootstrap artifacts, generated by this same compiler built as
    // suss-compile-generator, whose identity is the same digest of the same
    // sources (#383). Core's source and import manifest are inputs too.
    for path in ["runtime/core-import/suss/core.sus", "runtime/core-import/manifest.json"] {
        println!("cargo:rerun-if-changed={}", root.join(path).display());
    }
    assert_eq!(
        suss_compile_generator::compiler_source_sha256(),
        identity,
        "suss-compile-generator was built from different sources"
    );
    let out = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    use suss_compile_generator::portable::{bootstrap, resolve::Phase};
    for phase in [Phase::Runtime, Phase::Macro] {
        let (wasm, manifest) = bootstrap::generate(phase)
            .unwrap_or_else(|error| panic!("bootstrap generation failed: {}", error.message));
        let name = bootstrap::phase_name(phase);
        std::fs::write(out.join(format!("{name}.wasm")), wasm).unwrap();
        let mut edn = bootstrap::manifest_edn(&manifest).unwrap();
        edn.push('\n');
        std::fs::write(out.join(format!("{name}.edn")), edn).unwrap();
    }
}
