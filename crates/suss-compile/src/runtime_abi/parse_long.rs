//! Original exact Clojure decimal-string parsing; no Java dependency.
use super::*;

pub(super) fn function(b: &mut Builder) {
    use Instruction::*;
    // Value0, length1, cursor2, negative3, digit4, magnitude5, limit6.
    let mut code = vec![
        LocalGet(0),
        RefTestNonNull(HeapType::Concrete(STRING)),
        I32Eqz,
        If(BlockType::Empty),
    ];
    code.extend(numeric::error("Expected string", nominal::ERROR_GLOBAL));
    code.extend([
        End,
        LocalGet(0),
        RefCastNonNull(HeapType::Concrete(STRING)),
        ArrayLen,
        LocalSet(1),
        LocalGet(1),
        I32Eqz,
        If(BlockType::Empty),
        sentinel_value(NIL),
        Return,
        End,
        LocalGet(0),
        RefCastNonNull(HeapType::Concrete(STRING)),
        I32Const(0),
        ArrayGetU(STRING),
        LocalTee(4),
        I32Const(45),
        I32Eq,
        LocalSet(3),
        LocalGet(3),
        LocalGet(4),
        I32Const(43),
        I32Eq,
        I32Or,
        If(BlockType::Empty),
        I32Const(1),
        LocalSet(2),
        End,
        LocalGet(2),
        LocalGet(1),
        I32Eq,
        If(BlockType::Empty),
        sentinel_value(NIL),
        Return,
        End,
        // The unsigned magnitude limit is MAX, or 2^63 for a negative input.
        I64Const(i64::MAX),
        LocalGet(3),
        I64ExtendI32U,
        I64Add,
        LocalSet(6),
        Block(BlockType::Empty),
        Loop(BlockType::Empty),
        LocalGet(2),
        LocalGet(1),
        I32GeU,
        BrIf(1),
        LocalGet(0),
        RefCastNonNull(HeapType::Concrete(STRING)),
        LocalGet(2),
        ArrayGetU(STRING),
        // Reuse the complete executing pinned-JVM UTF-16 digit domain.
        Call(b.names["decimal-context-digit"]),
        LocalTee(4),
        I32Const(0),
        I32LtS,
        If(BlockType::Empty),
        sentinel_value(NIL),
        Return,
        End,
        // Check before multiplication; no double, wraparound or temporary BigInt.
        LocalGet(5),
        LocalGet(6),
        LocalGet(4),
        I64ExtendI32U,
        I64Sub,
        I64Const(10),
        I64DivU,
        I64GtU,
        If(BlockType::Empty),
        sentinel_value(NIL),
        Return,
        End,
        LocalGet(5),
        I64Const(10),
        I64Mul,
        LocalGet(4),
        I64ExtendI32U,
        I64Add,
        LocalSet(5),
        LocalGet(2),
        I32Const(1),
        I32Add,
        LocalSet(2),
        Br(0),
        End,
        End,
        LocalGet(3),
        If(BlockType::Result(ValType::I64)),
        I64Const(0),
        LocalGet(5),
        I64Sub,
        Else,
        LocalGet(5),
        End,
        Call(b.names["long-box"]),
    ]);
    b.function_with_locals(
        "number-parse-decimal-long",
        &[VALUE],
        &[VALUE],
        &[(4, ValType::I32), (2, ValType::I64)],
        &code,
    );
}
